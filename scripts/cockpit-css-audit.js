#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const outPath = process.argv[2] || path.join(root, 'docs/_audit/module-css-audit-2026-06-02.md');
const skipDirs = new Set(['node_modules', '.git', '.next', 'dist', 'build']);
const hexRe = /#[0-9a-fA-F]{3,8}\b/g;
const fontPxRe = /font-size\s*:\s*[0-9.]+px/g;
const localThemeRe = /(prefers-color-scheme|data-theme|\[data-theme|\.dark\b|\.light\b)/g;
const colorPropRe = /\b(?:color|background|background-color|border-color|box-shadow)\s*:/g;

function walkFiles(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (skipDirs.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkFiles(full, acc);
    else if (/\.(css|html)$/.test(entry.name)) acc.push(full);
  }
  return acc;
}

function countMatches(text, regex) {
  const matches = text.match(regex);
  return matches ? matches.length : 0;
}

function collectModule(baseDir, moduleName) {
  const dir = path.join(baseDir, moduleName);
  const files = walkFiles(dir).filter((file) => {
    try { return fs.statSync(file).size < 3_000_000; } catch { return false; }
  });
  const stat = {
    module: moduleName,
    files: 0,
    lines: 0,
    hex: 0,
    fontPx: 0,
    localTheme: 0,
    colorProps: 0,
    estimate: '0.5d',
  };
  for (const file of files) {
    let text = '';
    try { text = fs.readFileSync(file, 'utf8'); } catch { continue; }
    stat.files += 1;
    stat.lines += text.split(/\r?\n/).length;
    stat.hex += countMatches(text, hexRe);
    stat.fontPx += countMatches(text, fontPxRe);
    stat.localTheme += countMatches(text, localThemeRe);
    stat.colorProps += countMatches(text, colorPropRe);
  }
  const effortScore = stat.hex + stat.fontPx + Math.round(stat.colorProps / 4) + stat.localTheme * 4;
  if (effortScore > 220) stat.estimate = '1.5d';
  else if (effortScore > 110) stat.estimate = '1.0d';
  return stat;
}

function listModules(baseDir) {
  if (!fs.existsSync(baseDir)) return [];
  return fs.readdirSync(baseDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

function table(rows) {
  const lines = [
    '| Module | Files | Lines | Hex colors | Font px | Local theme refs | Color props | Estimate |',
    '|---|---:|---:|---:|---:|---:|---:|---:|',
  ];
  for (const row of rows) {
    lines.push(`| ${row.module} | ${row.files} | ${row.lines} | ${row.hex} | ${row.fontPx} | ${row.localTheme} | ${row.colorProps} | ${row.estimate} |`);
  }
  return lines.join('\n');
}

const runtimeBase = path.join(root, 'shell-ui/modules');
const sourceBase = path.join(root, 'sub-modules');
const runtimeRows = listModules(runtimeBase).map((name) => collectModule(runtimeBase, name));
const sourceRows = listModules(sourceBase).map((name) => collectModule(sourceBase, name));
const topRuntime = [...runtimeRows].sort((a, b) => (b.hex + b.fontPx + b.localTheme * 4) - (a.hex + a.fontPx + a.localTheme * 4)).slice(0, 5);

const report = `# Module CSS Audit - 2026-06-02

> Generated by \`node scripts/cockpit-css-audit.js\`.
> Scope: F-M1 token migration sizing. This report is read-only evidence; it does not modify module source code.

## Runtime Module Pages

These are the primary pages served by the Shell from \`shell-ui/modules\`.

${table(runtimeRows)}

## Highest Migration Candidates

${topRuntime.map((row, index) => `${index + 1}. \`${row.module}\`: ${row.hex} hex colors, ${row.fontPx} font-size px declarations, ${row.localTheme} local theme refs`).join('\n')}

## Source Sub-Modules Reference

These legacy/source directories remain useful reference input, but runtime migration should follow the Shell-served pages first unless a route serves a sub-module asset directly.

${table(sourceRows)}

## Acceptance Notes

- Runtime table contains ${runtimeRows.length} modules.
- No dependencies are required; the script uses Node.js built-ins only.
- Re-run after each token migration package and compare the hex/font/theme counts.
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, report);
console.log(`wrote ${path.relative(root, outPath)}`);
console.log(`runtime modules: ${runtimeRows.length}`);

