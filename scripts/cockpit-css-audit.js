function walkByExt(dir, exts, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (skipDirs.has(entry.name) || entry.name === '_archive' || entry.name.startsWith('.backup-')) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkByExt(full, exts, acc);
    else if (exts.some((ext) => entry.name.endsWith(ext))) acc.push(full);
  }
  return acc;
}

function countRegexInFiles(files, regex) {
  let total = 0;
  for (const file of files) {
    let text = '';
    try { text = fs.readFileSync(file, 'utf8'); } catch { continue; }
    total += countMatches(text, regex);
  }
  return total;
}

function countImportantLines(files) {
  let total = 0;
  for (const file of files) {
    let text = '';
    try { text = fs.readFileSync(file, 'utf8'); } catch { continue; }
    total += text.split(/\r?\n/).filter((line) => line.includes('!important')).length;
  }
  return total;
}

function countDuplicateCss(files) {
  const map = new Map();
  for (const file of files) {
    let buf;
    try { buf = fs.readFileSync(file); } catch { continue; }
    const h = crypto.createHash('md5').update(buf).digest('hex');
    if (!map.has(h)) map.set(h, []);
    map.get(h).push(file);
  }
  return [...map.values()].filter((items) => items.length > 1).length;
}

function collectStyleHealth() {
  const shellCss = walkByExt(path.join(root, 'shell-ui'), ['.css']).filter((file) => {
    const rel = path.relative(root, file);
    return !rel.startsWith('shell-ui/modules/');
  });
  const subCss = walkByExt(path.join(root, 'sub-modules'), ['.css']);
  const allCss = [...shellCss, ...walkByExt(path.join(root, 'shell-ui/modules'), ['.css']), ...subCss];
  const shellJs = walkByExt(path.join(root, 'shell-ui/modules'), ['.js']);
  const subJs = walkByExt(path.join(root, 'sub-modules'), ['.js']);
  const serverPath = path.join(root, 'server.js');
  const serverText = fs.existsSync(serverPath) ? fs.readFileSync(serverPath, 'utf8') : '';
  const cacheFiles = [...walkByExt(path.join(root, 'shell-ui'), ['.html', '.js']), ...walkByExt(path.join(root, 'sub-modules'), ['.html', '.js'])];
  if (fs.existsSync(serverPath)) cacheFiles.push(serverPath);
  const cacheSet = new Set();
  for (const file of cacheFiles) {
    let text = '';
    try { text = fs.readFileSync(file, 'utf8'); } catch { continue; }
    for (const m of text.match(/\?v=[0-9a-zA-Z._-]+/g) || []) cacheSet.add(m);
  }
  const backupFiles = [...walkByExt(path.join(root, 'shell-ui'), ['.bak', '.original']), ...walkByExt(path.join(root, 'sub-modules'), ['.bak', '.original'])]
    .filter((file) => !file.includes('/docs/backups/'));
  return {
    shellCssFiles: shellCss.length,
    subModuleCssFiles: subCss.length,
    importantTotal: countImportantLines(allCss),
    setProperty: countMatches(fs.existsSync(path.join(root, 'shell-ui/cockpit-ui-polish.js')) ? fs.readFileSync(path.join(root, 'shell-ui/cockpit-ui-polish.js'), 'utf8') : '', /setProperty/g),
    embedStyleAssignShell: countRegexInFiles(shellJs, /\.style\.[a-zA-Z-]+\s*=/g),
    embedStyleAssignSub: countRegexInFiles(subJs, /\.style\.[a-zA-Z-]+\s*=/g),
    bakFilesMainline: backupFiles.length,
    cacheBustVariants: cacheSet.size,
    deadStringCount: countMatches(serverText, /unified-animations|module-enhancements|light-theme/g),
    duplicateCss: countDuplicateCss([...walkByExt(path.join(root, 'shell-ui/modules'), ['.css']), ...subCss]),
  };
}

function runStyleHealthGuard() {
  const thresholdPath = path.join(root, 'scripts/.style-thresholds.json');
  if (!fs.existsSync(thresholdPath)) return;
  const thresholds = JSON.parse(fs.readFileSync(thresholdPath, 'utf8'));
  const metrics = collectStyleHealth();
  const violations = [];
  for (const [key, limit] of Object.entries(thresholds)) {
    const value = metrics[key];
    if (typeof value === 'number' && value > limit) violations.push(`${key}: ${value} > ${limit}`);
  }
  console.log('=== Style health guard ===');
  for (const [key, value] of Object.entries(metrics)) {
    const limit = thresholds[key];
    const suffix = limit === undefined ? ' (reported)' : (value > limit ? ` FAIL > ${limit}` : ` OK <= ${limit}`);
    console.log(`${key.padEnd(22)}: ${value}${suffix}`);
  }
  if (violations.length) {
    console.log('\nViolations:');
    for (const item of violations) console.log('  - ' + item);
    process.exitCode = 1;
  }
}

runStyleHealthGuard();
