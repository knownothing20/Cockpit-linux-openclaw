#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const modulesDir = path.join(root, 'shell-ui/modules');
const manifestDir = path.join(root, 'modules');
const args = process.argv.slice(2);
const checkMode = args.includes('--check');
const outputArg = args.find((arg) => arg !== '--check');
const dateStamp = process.env.COCKPIT_AUDIT_DATE || new Intl.DateTimeFormat('en-CA', {
  timeZone: process.env.TZ || 'Asia/Shanghai',
}).format(new Date());
const outPath = outputArg || path.join(root, `docs/_audit/unified-style-elements-matrix-${dateStamp}.md`);

const sharedElements = [
  ['Page', ['oc-page', 'oc-page-nested']],
  ['Header', ['oc-page-header', 'oc-card-header']],
  ['Toolbar', ['oc-toolbar']],
  ['Tabs', ['oc-tabs', 'oc-tab', 'oc-tab-content']],
  ['Card', ['oc-card', 'oc-card-body', 'oc-card-flat']],
  ['Form', ['oc-form-row', 'oc-field-label', 'oc-input', 'oc-select']],
  ['Button', ['oc-btn']],
  ['Badge/Chip', ['oc-badge', 'oc-chip']],
  ['List/Table', ['oc-list', 'oc-list-item', 'oc-table']],
  ['Empty', ['oc-empty']],
  ['Pagination', ['oc-pagination']],
  ['Switch', ['oc-switch', 'oc-switch-slider']],
  ['Modal/Toast', ['oc-modal', 'oc-modal-overlay', 'gw-toast']],
  ['Progress/Stats', ['oc-progress', 'oc-stat-grid', 'oc-stat-item']],
  ['Layout Utility', ['oc-flex-gap-4', 'oc-flex-gap-6', 'oc-flex-gap-8', 'oc-flex-gap-16', 'oc-grid']],
];

const problemPatterns = [
  ['important', /!important/g],
  ['patch words', /\b(?:layout-fix|hotfix|final-lock|hard-lock)\b|补丁式/g],
  ['inline style', /style\s*=/g],
  ['inline flex gap', /style\s*=\s*["'][^"']*display\s*:\s*flex[^"']*gap\s*:\s*(?:4|6|8|16)px|style\s*=\s*["'][^"']*gap\s*:\s*(?:4|6|8|16)px[^"']*display\s*:\s*flex/g],
  ['external startup asset', /<(?:script|link|img|iframe)\b[^>]+(?:src|href)\s*=\s*["']https?:\/\//gi],
  ['module generic card', /\b(?:status-card|skill-card|feature-item|change-item|section-card)\b/g],
  ['legacy shared aliases', /class\s*=\s*["'](?:empty-state|field-label|switch|switch-slider|sm-empty-state|sc-empty-state|session-empty-state)(?:\s|["'])|class\s*=\s*["'][^"']+\s(?:empty-state|field-label|switch|switch-slider|sm-empty-state|sc-empty-state|session-empty-state)(?:\s|["'])/g],
  ['private generic badges', /\b(?:type-badge|session-chip|sm-status-dot|status-badge|detection-tag|gw-enabled-badge|gw-context-badge)\b|class\s*=\s*["'](?:chip(?:\s|["'])|[^"']+\schip(?:\s|["']))/g],
];

function read(file) {
  try { return fs.readFileSync(file, 'utf8'); } catch { return ''; }
}

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, acc);
    else if (/\.(html|js|css)$/.test(entry.name)) acc.push(full);
  }
  return acc;
}

function count(text, re) {
  const m = text.match(re);
  return m ? m.length : 0;
}

function moduleManifests() {
  return fs.readdirSync(manifestDir)
    .filter((name) => name.endsWith('.module.json'))
    .map((name) => JSON.parse(read(path.join(manifestDir, name))))
    .sort((a, b) => (a.order || 99) - (b.order || 99) || a.id.localeCompare(b.id));
}

function collectModule(id) {
  const dir = path.join(modulesDir, id);
  const files = walk(dir);
  const text = files.map(read).join('\n');
  const elements = sharedElements.map(([label, classes]) => {
    const total = classes.reduce((sum, cls) => sum + count(text, new RegExp(`\\b${cls}\\b`, 'g')), 0);
    return { label, total };
  });
  const problems = Object.fromEntries(problemPatterns.map(([label, re]) => [label, count(text, re)]));
  const ocClassCount = count(text, /\boc-[a-z0-9-]+\b/g);
  // 资源 URL 的 query 串（如 ?v=20261010-fm-docs-real-pct）不是类名，先剥离再提取，避免版本串被误判为模块私有类。
  const textNoQuery = text.replace(/(\.(?:css|js|mjs|json|html|svg|png|jpe?g|gif|webp|ico|woff2?|ttf|map))\?[^"'\s>)]*/gi, '$1');
  const moduleClassHints = Array.from(new Set((textNoQuery.match(/\b(?:sm|fm|gw|models|session|config|robots|task|memory|applist)-[a-z0-9-]+\b/g) || []))).slice(0, 12);
  return { id, files, elements, problems, ocClassCount, moduleClassHints };
}

function mark(n) {
  if (n > 0) return String(n);
  return '-';
}

const manifests = moduleManifests();
const rows = manifests.map((m) => ({ manifest: m, stat: collectModule(m.id) }));

const lines = [];
lines.push(`# Unified Style Elements Matrix - ${dateStamp}`);
lines.push('');
lines.push('> Generated by `node scripts/audit-unified-style-elements.js`.');
lines.push('> Purpose: make shared design-system adoption explicit before further visual refactors.');
lines.push('');
lines.push('## Shared Element Contract');
lines.push('');
lines.push('| Element | Shared classes | Rule |');
lines.push('|---|---|---|');
lines.push('| Page | `.oc-page`, `.oc-page-nested` | Every module gets one page shell; module CSS may only define business layout inside it. |');
lines.push('| Header | `.oc-page-header`, `.oc-card-header` | Titles, subtitles, and actions follow shared header spacing. |');
lines.push('| Toolbar | `.oc-toolbar` | Filter/action rows use shared toolbar alignment; one-off margin stays local only when visual equivalence requires it. |');
lines.push('| Tabs | `.oc-tabs`, `.oc-tab`, `.oc-tab-content` | Navigation tabs share state classes and underline treatment. |');
lines.push('| Cards | `.oc-card`, `.oc-card-body`, `.oc-card-flat` | Generic cards are shared; business-specific cards keep module classes only for unique state visuals. |');
lines.push('| Forms | `.oc-form-row`, `.oc-field-label`, `.oc-input`, `.oc-select` | Form rows and labels are shared; exact width constraints can remain local. |');
lines.push('| Buttons | `.oc-btn` variants | All command buttons use shared button variants. |');
lines.push('| Badge/Chip | `.oc-badge`, `.oc-chip` | Status and metadata badges use shared variants. |');
lines.push('| List/Table | `.oc-list`, `.oc-list-item`, `.oc-table` | Repeated rows and tabular data use shared list/table surfaces. |');
lines.push('| Empty/Pagination/Switch | `.oc-empty`, `.oc-pagination`, `.oc-switch` | Common control states are shared. |');
lines.push('| Modal/Toast/Progress/Stats | `.oc-modal`, `.gw-toast`, `.oc-progress`, `.oc-stat-*` | Shared overlays and data-display primitives are reused before adding module CSS. |');
lines.push('| Layout utility | `.oc-flex-gap-*`, `.oc-grid*` | Utilities express raw layout values only; they do not encode module-specific fixes. |');
lines.push('');
lines.push('## Module Adoption Matrix');
lines.push('');
lines.push('| Module | Page | Header | Toolbar | Tabs | Card | Form | Button | Badge/Chip | List/Table | Empty | Pagination | Switch | Modal/Toast | Progress/Stats | Layout util | Inline style | Flex-gap inline | Patch words | Generic private components | Legacy shared aliases | Private generic badges | Notes |');
lines.push('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|');
for (const { manifest, stat } of rows) {
  const e = Object.fromEntries(stat.elements.map((item) => [item.label, item.total]));
  const noteParts = [];
  if (stat.moduleClassHints.length) noteParts.push(`module classes: ${stat.moduleClassHints.join(', ')}`);
  if (stat.problems['patch words']) noteParts.push('review patch-like names/text');
  if (stat.problems['module generic card']) noteParts.push('generic private components remain');
  if (stat.problems['legacy shared aliases']) noteParts.push('legacy shared aliases remain');
  if (stat.problems['private generic badges']) noteParts.push('private generic badges remain');
  lines.push(`| ${manifest.id} | ${mark(e.Page)} | ${mark(e.Header)} | ${mark(e.Toolbar)} | ${mark(e.Tabs)} | ${mark(e.Card)} | ${mark(e.Form)} | ${mark(e.Button)} | ${mark(e['Badge/Chip'])} | ${mark(e['List/Table'])} | ${mark(e.Empty)} | ${mark(e.Pagination)} | ${mark(e.Switch)} | ${mark(e['Modal/Toast'])} | ${mark(e['Progress/Stats'])} | ${mark(e['Layout Utility'])} | ${stat.problems['inline style']} | ${stat.problems['inline flex gap']} | ${stat.problems['patch words']} | ${stat.problems['module generic card']} | ${stat.problems['legacy shared aliases']} | ${stat.problems['private generic badges']} | ${noteParts.join('; ') || '-'} |`);
}
lines.push('');
lines.push('## Migration Decisions');
lines.push('');
lines.push('- Shared component: page shell, headers, toolbars, tabs, cards, forms, buttons, badges, lists, empty states, pagination, switches, modals, toasts, progress bars, and stats.');
lines.push('- Shared utility: raw layout helpers such as flex gap and grid helpers. These must stay value-only and must not become module overrides.');
lines.push('- Module-specific: business structures such as AI Growth workbench columns, Robots agent topology/details, File Manager browser panes, Inspira distillation workbench, and module-specific state illustrations.');
lines.push('- Prohibited: `!important`, patch/fix/lock style blocks, broad module overrides of shared components, and new private generic components when an `.oc-*` primitive exists.');
lines.push('- Startup assets must be local. Do not load `<script>`, stylesheet, image, or iframe resources from external HTTP(S) URLs in cockpit modules.');
lines.push('');
lines.push('## Next Refactor Queue');
lines.push('');
for (const { manifest, stat } of rows) {
  const issues = [];
  if (stat.problems.important) issues.push(`${stat.problems.important} !important`);
  if (stat.problems['inline style']) issues.push(`${stat.problems['inline style']} inline style`);
  if (stat.problems['inline flex gap']) issues.push(`${stat.problems['inline flex gap']} inline flex-gap`);
  if (stat.problems['patch words']) issues.push(`${stat.problems['patch words']} patch-like references`);
  if (stat.problems['module generic card']) issues.push(`${stat.problems['module generic card']} generic private component references`);
  if (stat.problems['legacy shared aliases']) issues.push(`${stat.problems['legacy shared aliases']} legacy shared aliases`);
  if (stat.problems['private generic badges']) issues.push(`${stat.problems['private generic badges']} private generic badges`);
  if (issues.length) lines.push(`- \`${manifest.id}\`: ${issues.join(', ')}.`);
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n') + '\n');
console.log(`wrote ${path.relative(root, outPath)}`);

if (checkMode) {
  const failures = [];
  for (const { manifest, stat } of rows) {
    for (const [label] of problemPatterns) {
      const total = stat.problems[label] || 0;
      if (total) failures.push(`${manifest.id}: ${total} ${label}`);
    }
  }
  if (failures.length) {
    console.error('Unified style audit failed:');
    for (const failure of failures) console.error(`- ${failure}`);
    process.exitCode = 1;
  } else {
    console.log('Unified style audit passed.');
  }
}
